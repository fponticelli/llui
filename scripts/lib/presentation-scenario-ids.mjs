// Render `registry/registry.json#productContract`'s scenario ids, per presentation family, as a
// TypeScript module whose values are LITERAL types.
//
// `compileScenarioFamily` (`@llui/cli/presentation-scenarios`) is exact: a family's definitions
// must be keyed by exactly the family's ProductContract scenario ids, so its catalog's
// `scenarioId` union is provably the set of scenarios the catalog carries. A JSON import types
// every id as `string`, which proves nothing, so the ids reach the type system through this
// generated module instead. `registry/registry.json` stays the ONE source of truth: this module
// is derived from it by `scripts/build-registry.mjs` (so `pnpm build:registry` and the site's
// `generate` rewrite it), `pnpm check:generated` diffs it, and
// `scripts/test/presentation-scenario-ids.test.ts` fails the moment it drifts. Even a stale
// copy cannot mistype a catalog: `compileScenarioFamily` cross-checks the ids against the
// contract it is handed at runtime and throws on any difference.
import path from 'node:path'
import { format, resolveConfig } from 'prettier'

/** Where the module lives: beside the family scenario definitions that import it. */
export const PRESENTATION_SCENARIO_IDS_PATH = path.join(
  'packages',
  'components',
  'test',
  'styles',
  'presentation-scenario-ids.ts',
)

/**
 * The per-family scenario ids of a product contract, in canonical contract order, families in
 * order of first appearance. Only `presentation.family` and `scenarioId` are read; the contract
 * itself is validated by `@llui/cli`'s schema wherever it is loaded.
 * @param {unknown} productContract
 * @returns {Map<string, string[]>}
 */
export function presentationScenarioIdsByFamily(productContract) {
  if (typeof productContract !== 'object' || productContract === null) {
    throw new Error('productContract must be an object')
  }
  /** @type {unknown} */
  const entries = Reflect.get(productContract, 'entries')
  if (!Array.isArray(entries)) throw new Error('productContract.entries must be an array')
  /** @type {Map<string, string[]>} */
  const byFamily = new Map()
  for (const [index, entry] of entries.entries()) {
    /** @type {unknown} */
    const presentation =
      typeof entry === 'object' && entry !== null ? Reflect.get(entry, 'presentation') : undefined
    /** @type {unknown} */
    const family =
      typeof presentation === 'object' && presentation !== null
        ? Reflect.get(presentation, 'family')
        : undefined
    /** @type {unknown} */
    const scenarioId =
      typeof entry === 'object' && entry !== null ? Reflect.get(entry, 'scenarioId') : undefined
    if (typeof family !== 'string' || typeof scenarioId !== 'string') {
      throw new Error(`productContract.entries[${index}] has no string family/scenarioId`)
    }
    const ids = byFamily.get(family) ?? []
    if (ids.includes(scenarioId)) {
      throw new Error(`duplicate scenarioId ${JSON.stringify(scenarioId)} in family ${family}`)
    }
    ids.push(scenarioId)
    byFamily.set(family, ids)
  }
  return byFamily
}

/**
 * The module's full, prettier-formatted source for `productContract`.
 * @param {unknown} productContract
 * @param {string} root repository root, for prettier's config resolution
 * @returns {Promise<string>}
 */
export async function renderPresentationScenarioIds(productContract, root) {
  const families = [...presentationScenarioIdsByFamily(productContract)]
  const body = families
    .map(
      ([family, ids]) =>
        `${JSON.stringify(family)}: { family: ${JSON.stringify(family)}, scenarioIds: [${ids
          .map((id) => JSON.stringify(id))
          .join(', ')}] },`,
    )
    .join('\n')
  const source = `// GENERATED by scripts/build-registry.mjs (scripts/lib/presentation-scenario-ids.mjs) from
// registry/registry.json#productContract. Do not edit: \`pnpm build:registry\` rewrites it, and
// \`pnpm check:generated\` and scripts/test/presentation-scenario-ids.test.ts fail when it drifts.
//
// Each presentation family's ProductContract scenario ids as LITERAL types, in canonical
// contract order: the \`PresentationScenarioFamilyIds\` that \`compileScenarioFamily\` checks a
// family's definitions against, key for key. A missing or an extra definition is a compile
// error, and the ids are cross-checked against the runtime contract when a catalog compiles.
import type { PresentationFamily } from '@llui/cli'
import type { PresentationScenarioFamilyIds } from '@llui/cli/presentation-scenarios'

export const PRESENTATION_SCENARIO_IDS = {
${body}
} as const satisfies {
  readonly [Family in PresentationFamily]: PresentationScenarioFamilyIds<Family>
}
`
  const filepath = path.join(root, PRESENTATION_SCENARIO_IDS_PATH)
  const options = (await resolveConfig(filepath)) ?? {}
  return format(source, { ...options, filepath })
}
